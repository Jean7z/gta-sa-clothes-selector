#!/usr/bin/env node
/*
 * Generates mod/selector_script.h from the CLEO-Android script blob.
 *
 * The script is a plain GTA:SA .csi bytecode stream (it uses only vanilla
 * opcodes), so it is embedded verbatim as a byte array and handed to the
 * game's own CTheScripts::StartNewScript loader. No interpreter involved.
 *
 * Usage: node tools/gen_script_header.js "<path to .csi>" <out header>
 */
'use strict';

const fs = require('fs');
const path = require('path');
const crypto = require('crypto');

const SRC = process.argv[2];
const OUT = process.argv[3];

if (!SRC || !OUT) {
    console.error('usage: node gen_script_header.js <input.csi> <output.h>');
    process.exit(2);
}

const bytes = fs.readFileSync(SRC);
const len = bytes.length;
const sha = crypto.createHash('sha256').update(bytes).digest('hex');

// 16 bytes per line, 0x%02X.
const lines = [];
for (let i = 0; i < len; i += 16) {
    const chunk = bytes.subarray(i, i + 16);
    const cells = Array.from(chunk, (b) => '0x' + b.toString(16).toUpperCase().padStart(2, '0'));
    // Trailing comma is valid C and lets the last line be emitted uniformly.
    lines.push('    ' + cells.join(',') + ',');
}

const header = `// Generated by tools/gen_script_header.js -- do not edit by hand.
//
// Source : ${path.basename(SRC)}
// Size   : ${len} bytes
// SHA256 : ${sha}
//
// This is the CLEO-Android script "${path.basename(SRC)}" in its raw .csi
// bytecode form. It uses only vanilla GTA:SA mobile opcodes, so the game's own
// CTheScripts::StartNewScript can load it directly.

#pragma once

static const unsigned char SELECTOR_SCRIPT[] = {
${lines.join('\n')}
};

static const unsigned int SELECTOR_SCRIPT_LEN = ${len};
`;

fs.writeFileSync(OUT, header);

console.log(`wrote ${OUT}`);
console.log(`  size   : ${len}`);
console.log(`  sha256 : ${sha}`);